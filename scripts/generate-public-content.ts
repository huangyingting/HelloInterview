import { readFile, writeFile } from 'node:fs/promises';
import { companies, levels, regions, practiceLabels, practiceTracks, problems, quizQuestions, quizTopics, tracks } from '../shared/catalog';
import { courses } from '../shared/courses';
import type { ProblemMetadata, TrackMetadata } from '../shared/types';

const metadata: TrackMetadata[] = tracks.map(track => ({
  id:track.id,title:track.title,short:track.short,description:track.description,color:track.color,
  lessons: track.lessons.map(lesson => ({
    id:lesson.id,title:lesson.title,group:lesson.group,minutes:lesson.minutes,summary:lesson.summary,
    premium:lesson.premium,objectives:lesson.objectives,sourceIds:lesson.sourceIds,
    relatedProblemIds:lesson.relatedProblemIds,quizTopic:lesson.quizTopic,
  })),
}));
const exercises: ProblemMetadata[] = problems.map(problem => ({
  id: problem.id, track: problem.track, title: problem.title, difficulty: problem.difficulty,
  description: problem.premium ? `Premium practice: ${problem.title}.` : problem.description,
  premium: problem.premium, hasWorkedCase: !!problem.workedCase, hasSolution: !!problem.solution,
  exampleCount: (problem.solution?.examples ?? problem.testCases ?? []).length,
  runnable: !!problem.testCases, caseSummary: problem.workedCase?.summary ?? '',
  calculationCount: problem.workedCase?.calculations.length ?? 0,
}));
const publicCourses=courses.map(course=>({
  id:course.id,title:course.title,description:course.description,track:course.track,premium:course.premium,
  units:course.units.map(unit=>({title:unit.title,steps:unit.steps.map(step=>({id:step.id,type:step.type,title:step.title,resource:step.resource,to:step.to}))})),
}));
const fields = { tracks: metadata, problems: exercises, quizTopics, questionIndex: quizQuestions.map(({ id, topic }) => ({ id, topic })), companies, levels, regions, practiceLabels, practiceTracks, courses: publicCourses,
  navigationTracks: metadata.map(({id,title,short,description,color})=>({id,title,short,description,color})) };
const types: Record<keyof typeof fields, string> = {
  tracks: 'TrackMetadata[]', problems: 'ProblemMetadata[]', quizTopics: '{ id: string; title: string; track: string; count: number }[]',
  questionIndex: '{ id: string; topic: string }[]', companies: 'string[]', levels: 'readonly Level[]',
  regions: "readonly ['Global', 'North America', 'Europe', 'Asia Pacific']", practiceLabels: 'Record<string, string>',
  practiceTracks: 'string[]', courses: 'Course[]',
  navigationTracks: "Pick<TrackMetadata, 'id' | 'title' | 'short' | 'description' | 'color'>[]",
};
const header = '// Generated by npm run content:metadata. Only public discovery fields belong here.\n';
function declarations(names: (keyof typeof fields)[]) {
  return names.map(name=>`export const ${name}: ${types[name]} = ${JSON.stringify(fields[name], null, 2)};`).join('\n')+'\n';
}
const outputs = new Map([
  ['shared/public-tracks.ts',header+"import type { TrackMetadata } from './types';\n"+declarations(['tracks'])+
    'export function getTrack(id: string) { return tracks.find(track => track.id === id); }\n'],
  ['shared/public-problems.ts',header+"import type { ProblemMetadata } from './types';\n"+declarations(['problems'])],
  ['shared/public-courses.ts',header+"import type { Course } from './types';\n"+declarations(['courses'])],
  ['shared/public-quiz.ts',header+declarations(['quizTopics','questionIndex'])],
  ['shared/public-navigation.ts',header+"import type { Level, TrackMetadata } from './types';\n"+
    declarations(['companies','levels','regions','practiceLabels','practiceTracks','navigationTracks'])],
  ['shared/public-catalog.ts',header+
    "export { tracks, getTrack } from './public-tracks';\n"+
    "export { problems } from './public-problems';\n"+
    "export { courses } from './public-courses';\n"+
    "export { quizTopics, questionIndex } from './public-quiz';\n"+
    "export { companies, levels, regions, practiceLabels, practiceTracks, navigationTracks } from './public-navigation';\n"],
]);
for(const [file,source] of outputs) {
  if(process.argv.includes('--check')) {
    if(await readFile(file,'utf8')!==source)throw new Error(`Public metadata is stale: ${file}. Run npm run content:metadata and commit its output.`);
  } else await writeFile(file,source);
}
